// Scope upstream CSS so the editor wears Stack Proc's skin without changing
// global controls or the separate workflow canvas. Pinned source remains auditable.
import postcss from 'postcss';
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const css = postcss.parse(await readFile(new URL('vendor/ontology-playground/src/styles/app.css', root), 'utf8'));
css.walkAtRules(/keyframes$/, (rule) => {
  const old = rule.params;
  rule.params = `sp-ontology-${old}`;
  css.walkDecls(/animation/, (decl) => {
    decl.value = decl.value.replace(new RegExp(`\\b${old}\\b`, 'g'), rule.params);
  });
});
css.walkRules((rule) => {
  // Tailwind already supplies the document reset. An unlayered upstream * reset
  // would erase padding on the official Untitled UI controls.
  if (rule.selector === '*') rule.walkDecls(/^(margin|padding)$/, (decl) => decl.remove());
  if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.map((selector) => {
    if (selector === ':root' || selector === 'body' || selector === 'html') return '.sp-ontology-playground';
    if (selector.startsWith('.light-theme')) return `.sp-ontology-playground${selector}`;
    return `.sp-ontology-playground ${selector}`;
  });
});
await writeFile(
  new URL('app/ontology-vendor.css', root),
  '/* Microsoft Ontology Playground · MIT. Generated by scripts/build-ontology.mjs; see vendor provenance. */\n' +
    css.toString(),
);
